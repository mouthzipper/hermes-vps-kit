#!/usr/bin/env bash
# User-level install (run as the VPS user, not root). Idempotent; replaced files are backed up as *.bak-<timestamp>.
# Installs dotfiles, Hermes config + profiles, skills, project dirs, systemd user units and herdr sessions.
# Toggles (env or .env): WITH_CLAUDE WITH_HERMES WITH_SLED WITH_HERDR WITH_SKILLS (1/0), SKIP_SYSTEMD=1
# Environment files are local operator input; single-quoted commands expand in the child shell.
# shellcheck disable=SC1091,SC2016
set -euo pipefail
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
[[ ${SKIP_REPO_ENV:-0} != 1 && -f "$REPO_DIR/.env" ]] && set -a && . "$REPO_DIR/.env" && set +a
[[ $EUID -ne 0 ]] || { echo "run install.sh as the VPS user, not root" >&2; exit 1; }
: "${WITH_CLAUDE:=1}" "${WITH_HERMES:=1}" "${WITH_SLED:=1}" "${WITH_HERDR:=1}" "${WITH_SKILLS:=1}" "${SKIP_SYSTEMD:=0}"
: "${HERMES_MAX_SUBAGENTS:=2}"
GIT_AUTHOR_NAME="${GIT_AUTHOR_NAME:-$(git config --global user.name || echo 'Your Name')}"
GIT_AUTHOR_EMAIL="${GIT_AUTHOR_EMAIL:-$(git config --global user.email || echo 'you@example.com')}"
TS="$(date +%Y%m%d%H%M%S)"
export PATH="$HOME/.local/bin:$HOME/.npm-global/bin:$PATH"

render() {
  RENDER_HOME="$HOME" RENDER_IP="${TAILSCALE_IP:-127.0.0.1}" RENDER_NAME="$GIT_AUTHOR_NAME" RENDER_EMAIL="$GIT_AUTHOR_EMAIL" python3 - "$1" <<'PYTHON'
import json, os, sys
from pathlib import Path
path = Path(sys.argv[1])
text = path.read_text()
values = dict(zip(('__HOME__', '__TAILSCALE_IP__', '__GIT_AUTHOR_NAME__', '__GIT_AUTHOR_EMAIL__'),
                  (os.environ['RENDER_HOME'], os.environ['RENDER_IP'], os.environ['RENDER_NAME'], os.environ['RENDER_EMAIL'])))
# JSON templates need string escaping as well as literal replacement.
import re
print(re.sub('|'.join(map(re.escape, values)), lambda m: json.dumps(values[m[0]])[1:-1] if path.suffix == '.json' else values[m[0]], text), end='')
PYTHON
}
# install_file TMP DEST MODE: copy if changed, backing up the old file
install_file() {
  local tmp="$1" dest="$2" mode="$3"; mkdir -p "$(dirname "$dest")"
  if [[ -f "$dest" ]] && cmp -s "$tmp" "$dest"; then rm -f "$tmp"; return; fi
  [[ -f "$dest" ]] && cp "$dest" "$dest.bak-$TS"
  install -m "$mode" "$tmp" "$dest"; rm -f "$tmp"; echo "  installed $dest"
}
place() { local t; t="$(mktemp)"; render "$1" > "$t"; install_file "$t" "$2" "${3:-644}"; }
# set_env FILE KEY VALUE: create/update KEY=VALUE in an env file (chmod 600)
set_env() {
  local f="$1" k="$2" v="$3"; mkdir -p "$(dirname "$f")"; [[ -f "$f" ]] || install -m 600 /dev/null "$f"
  python3 - "$f" "$k" "$v" <<'PYTHON'
from pathlib import Path
import shlex, sys
p, key, value = Path(sys.argv[1]), sys.argv[2], sys.argv[3]
lines = p.read_text().splitlines()
lines = [line for line in lines if not line.startswith(key + '=')]
p.write_text('\n'.join(lines + [key + '=' + shlex.quote(value)]) + '\n')
p.chmod(0o600)
PYTHON
}

# hermes_config: minimal Hermes config from .env. Model keys only when set; secrets stay in env files.
hermes_config() {
  HERMES_PROVIDER="${HERMES_PROVIDER:-}" HERMES_MODEL="${HERMES_MODEL:-}" HERMES_BASE_URL="${HERMES_BASE_URL:-}" \
  HERMES_API_KEY_ENV="${HERMES_API_KEY_ENV:-}" HERMES_SUBAGENT_MODEL="${HERMES_SUBAGENT_MODEL:-}" \
  HERMES_MAX_SUBAGENTS="$HERMES_MAX_SUBAGENTS" python3 - <<'PYTHON'
import json, os, re
v = os.environ
print('# Generated by hermes-vps-kit install.sh; secrets stay in env files.')
def field(name, value):
    if value:
        print('  ' + name + ': ' + json.dumps(value))  # JSON strings are valid YAML scalars.
if any(v[k] for k in ('HERMES_PROVIDER', 'HERMES_MODEL', 'HERMES_BASE_URL')):
    print('model:')
    for name, key in [('default', 'HERMES_MODEL'), ('provider', 'HERMES_PROVIDER'), ('base_url', 'HERMES_BASE_URL')]:
        field(name, v[key])
    key = v['HERMES_API_KEY_ENV']
    if key:
        if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', key):
            raise SystemExit('HERMES_API_KEY_ENV must be an environment variable name')
        field('api_key', '${' + key + '}')
print('delegation:')
field('model', v['HERMES_SUBAGENT_MODEL'])
if v['HERMES_SUBAGENT_MODEL']:
    field('provider', v['HERMES_PROVIDER'])
    field('base_url', v['HERMES_BASE_URL'])
count = v['HERMES_MAX_SUBAGENTS']
if not re.fullmatch(r'[1-9][0-9]*', count):
    raise SystemExit('HERMES_MAX_SUBAGENTS must be a positive integer')
print('  max_concurrent_children: ' + count)
print('  max_spawn_depth: 1\n  subagent_auto_approve: false')
PYTHON
}

echo "==> dotfiles"
while IFS= read -r -d '' f; do
  rel="${f#"$REPO_DIR/dotfiles/"}"; mode=644; [[ -x "$f" ]] && mode=755
  [[ "$rel" == .claude/settings.json ]] && continue
  [[ "$WITH_CLAUDE" != 1 && "$rel" == .claude/* ]] && continue
  [[ "$WITH_SLED" != 1 && "$rel" == sled-run.sh ]] && continue
  place "$f" "$HOME/$rel" "$mode"
done < <(find "$REPO_DIR/dotfiles" -type f -print0)

if [[ "$WITH_HERMES" == 1 ]]; then
  PDIR="${HERMES_PROFILES_DIR:-}"
  [[ -z "$PDIR" && -d "$REPO_DIR/profiles.local" ]] && PDIR="$REPO_DIR/profiles.local"
  PDIR="${PDIR:-$REPO_DIR/examples/profiles}"
  echo "==> Hermes config + profiles from $PDIR"
  t="$(mktemp)"; hermes_config > "$t"
  if [[ -n "${TELEGRAM_USER_ID:-}" ]]; then
    [[ "${TELEGRAM_USER_ID}" =~ ^-?[0-9]+$ ]] || { echo "TELEGRAM_USER_ID must be numeric" >&2; exit 2; }
    printf 'platforms:\n  telegram:\n    enabled: true\n    home_channel:\n      platform: telegram\n      chat_id: "%s"\n      name: owner\n      user_id: "%s"\n' "$TELEGRAM_USER_ID" "$TELEGRAM_USER_ID" >> "$t"
  fi
  install_file "$t" "$HOME/.hermes/config.yaml" 600
  if [[ ! -f "$HOME/.hermes/.env" ]]; then install -m 600 "$REPO_DIR/hermes/env.example" "$HOME/.hermes/.env"; echo "  created ~/.hermes/.env: add TELEGRAM_BOT_TOKEN etc."
  elif ! grep -q '^TELEGRAM_BOT_TOKEN=' "$HOME/.hermes/.env"; then cat "$REPO_DIR/hermes/env.example" >> "$HOME/.hermes/.env"; echo "  appended Telegram template to ~/.hermes/.env"; fi
  if [[ -n "${TELEGRAM_ALLOWED_USERS:-}" ]]; then
    set_env "$HOME/.hermes/.env" TELEGRAM_ALLOWED_USERS "$TELEGRAM_ALLOWED_USERS"
  fi
  for p in "$PDIR"/*/; do
    [[ -d "$p" ]] || continue; n="$(basename "$p")"
    for f in "$p"*; do [[ -f "$f" ]] && place "$f" "$HOME/.hermes/profiles/$n/$(basename "$f")" 600; done
    [[ -f "$p/config.yaml" ]] || { t="$(mktemp)"; hermes_config > "$t"; install_file "$t" "$HOME/.hermes/profiles/$n/config.yaml" 600; }
    [[ -f "$HOME/.hermes/profiles/$n/.env" ]] || install -m 600 /dev/null "$HOME/.hermes/profiles/$n/.env"
    t="$(mktemp)"; printf '#!/bin/sh\n# shortcut for: hermes -p %s\nexec "${HERMES_BIN:-hermes}" -p %s "$@"\n' "$n" "$n" > "$t"
    install_file "$t" "$HOME/.local/bin/$n" 755
  done
  if [[ -d "$HOME/.hermes/profiles/reviewer" ]]; then
    set_env "$HOME/.hermes/profiles/reviewer/.env" REVIEW_ORGS "${REVIEW_ORGS:-}"
    set_env "$HOME/.hermes/profiles/reviewer/.env" PR_REVIEWER_NO_BUILD 1
    set_env "$HOME/.hermes/profiles/reviewer/.env" TRUSTED_AUTHORS "${TRUSTED_AUTHORS:-}"
    [[ -n "${REVIEW_ORGS:-}" ]] || echo "  note: REVIEW_ORGS is empty; set it in .env and re-run to scope the reviewer"
  fi
fi

if [[ "$WITH_HERMES" == 1 && -z "${HERMES_MODEL:-}${HERMES_PROVIDER:-}" ]]; then
  echo "  note: no HERMES_PROVIDER/HERMES_MODEL in .env; run 'hermes model' to pick one (or set them and re-run install.sh)"
fi
[[ -n "${HERMES_API_KEY_ENV:-}" ]] && echo "  note: put ${HERMES_API_KEY_ENV}=<your key> in ~/.hermes/.env (the config only references the variable name)"

if [[ "$WITH_CLAUDE" == 1 ]]; then
  echo "==> Claude Code settings"
  t="$(mktemp)"; render "$REPO_DIR/dotfiles/.claude/settings.json" > "$t.src"
  CLAUDE_MODEL="${CLAUDE_MODEL:-}" CLAUDE_SUBAGENT_MODEL="${CLAUDE_SUBAGENT_MODEL:-}" python3 - "$t.src" > "$t" <<'PY'
import json, os, sys
d = json.load(open(sys.argv[1]))
if os.environ["CLAUDE_MODEL"]: d["model"] = os.environ["CLAUDE_MODEL"]
if os.environ["CLAUDE_SUBAGENT_MODEL"]: d.setdefault("env", {})["CLAUDE_CODE_SUBAGENT_MODEL"] = os.environ["CLAUDE_SUBAGENT_MODEL"]
print(json.dumps(d, indent=2))
PY
  rm -f "$t.src"
  install_file "$t" "$HOME/.claude/settings.json" 644
fi

if [[ "$WITH_SKILLS" == 1 ]]; then
  echo "==> skills (pstack + herdr)"
  "$REPO_DIR/scripts/install-skills.sh" || echo "  skills install failed (non-fatal); re-run scripts/install-skills.sh"
fi

echo "==> projects layout"
for d in ${PROJECTS:-}; do mkdir -p "$HOME/projects/$d"; done
mkdir -p "$HOME/projects/logs"

# sudo -iu / su don't set these; without them systemctl --user can't reach the (lingering) user manager
if [[ -z "${XDG_RUNTIME_DIR:-}" && -d "/run/user/$(id -u)" ]]; then
  XDG_RUNTIME_DIR="/run/user/$(id -u)"
  export XDG_RUNTIME_DIR
  export DBUS_SESSION_BUS_ADDRESS="unix:path=$XDG_RUNTIME_DIR/bus"
fi
if [[ "$SKIP_SYSTEMD" == 1 ]] || ! systemctl --user show-environment >/dev/null 2>&1; then
  echo "==> systemd user manager not available (or SKIP_SYSTEMD=1): skipping units and herdr sessions"
  echo "Done."; exit 0
fi
echo "==> systemd user units"
UNITS=()
GATEWAY_BLOCKED=0
if [[ "$WITH_HERMES" == 1 ]]; then
  # The gateway reads this file; check the same source before enabling it.
  allowed_users="$(
    [[ ! -f "$HOME/.hermes/.env" ]] || . "$HOME/.hermes/.env"
    printf '%s' "${TELEGRAM_ALLOWED_USERS:-}"
  )"
  if [[ -z "${allowed_users//[[:space:],]/}" ]]; then
    systemctl --user disable --now hermes-gateway.service 2>/dev/null || true
    echo "Refusing to enable/start Hermes gateway: TELEGRAM_ALLOWED_USERS is empty. Set explicit user IDs in ~/.hermes/.env, then re-run install.sh." >&2
    GATEWAY_BLOCKED=1
  else
    UNITS+=(hermes-gateway.service)
  fi
fi
[[ "$WITH_SLED" == 1 ]] && UNITS+=(sled.service)
[[ "$WITH_SLED" == 1 && -n "${TAILSCALE_IP:-}" && "${SLED_TAILNET_SOCAT:-0}" == 1 ]] && UNITS+=(sled-tailnet.service)
for u in "$REPO_DIR"/systemd/user/*; do place "$u" "$HOME/.config/systemd/user/$(basename "$u")"; done
systemctl --user daemon-reload
for u in "${UNITS[@]}"; do systemctl --user enable "$u"; done
[[ "$WITH_HERDR" == 1 ]] && "$REPO_DIR/scripts/herdr-sessions.sh"
echo "Units enabled (not started). After logins: systemctl --user start ${UNITS[*]}"

# Independent units and sessions are installed even when the gateway is refused.
[[ $GATEWAY_BLOCKED == 0 ]] || exit 1
